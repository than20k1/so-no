/** Như `t` của useI18n nhưng hiểu thêm khoá của phần tài khoản. */
export function useAccountT() {
  const { lang, t } = useI18n();
  return (key: AccountKey | TKey, params?: Record<string, string | number>): string => {
    if (!(key in accountVi)) return t(key as TKey, params);
    let text = (lang === "en" ? accountEn : accountVi)[key as AccountKey];
    if (params) for (const [k, v] of Object.entries(params)) text = text.replaceAll(`{${k}}`, String(v));
    return text;
  };
}
