/** Như `t` của useI18n nhưng hiểu thêm khoá của phần Chia tiền. */
export function useGroupsT() {
  const { lang, t } = useI18n();
  return (key: GroupsKey | TKey, params?: Record<string, string | number>): string => {
    if (!(key in groupsVi)) return t(key as TKey, params);
    let text = (lang === "en" ? groupsEn : groupsVi)[key as GroupsKey];
    if (params) for (const [k, v] of Object.entries(params)) text = text.replaceAll(`{${k}}`, String(v));
    return text;
  };
}

/** Mã lỗi (thao tác trên máy hoặc API) → khoá chuỗi. */
export function groupErrorKey(code: string): GroupsKey {
  const map: Record<string, GroupsKey> = {
    empty_name: "errEmptyName",
    name_too_long: "errNameTooLong",
    name_taken: "errNameTaken",
    invalid_weight: "errInvalidWeight",
    too_many_members: "errTooManyMembers",
    limit: "errTooManyMembers",
    member_in_use: "memberInUse",
    invalid_amount: "errInvalidAmount",
    no_participants: "errNoParticipants",
    same_person: "errSamePerson",
    not_found: "errNotFound",
    invalid_link: "errInvalidLink",
    taken: "errTaken",
    too_many_attempts: "errJoinTooMany",
    forbidden: "errForbidden",
    offline: "needOnline",
  };
  return map[code] ?? "groupErrServer";
}
